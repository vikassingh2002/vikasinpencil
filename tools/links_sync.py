#!/usr/bin/env python3
"""Fill in titles, makers and pictures for the links in content/references.js.

Every entry in the "log" that has a link gets looked up once: its title, who
made it (director, author, channel, show), its year and a picture. What it
finds goes in content/media.js and the picture in assets/refs/. Anything you
typed yourself in references.js (a title, a "by") always wins on the site.

Runs every morning after the Goodreads sync. By hand:  python tools/links_sync.py
Standard library only. A link that can't be read is tried again next time and
never stops the sync.
"""
import hashlib
import html
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from datetime import date
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFERENCES = ROOT / "content" / "references.js"
OUT = ROOT / "content" / "media.js"
PICTURES = ROOT / "assets" / "refs"
USER_AGENT = "Mozilla/5.0 (compatible; vikasinpencil-sync/1.0; +https://vikasinpencil.com)"
WIKIDATA = "https://www.wikidata.org/w/api.php"

HEADER = """/* =============================================================
   MEDIA: generated by tools/links_sync.py from the links in the
   "log" of content/references.js. Don't edit by hand: write titles
   or notes in references.js instead, and they win over this file.
   ============================================================= */
window.NB = window.NB || {};

"""


def get(url, accept="*/*", limit=3_000_000):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": accept, "Accept-Language": "en"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read(limit), resp.headers.get_content_charset() or "utf-8"


def get_json(url):
    data, charset = get(url, "application/json")
    return json.loads(data.decode(charset, "replace"))


def squash(s):
    return re.sub(r"\s+", " ", html.unescape(s or "")).strip()


# ---------- reading the links out of references.js ----------

def log_links(text):
    """(link, type) for every object in the log that has a link. Comments (and their examples) don't count."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"(?m)^\s*//.*$", "", text)
    found = []
    for obj in re.finditer(r"\{[^{}]*?\blink:\s*\"(https?://[^\"]+)\"[^{}]*\}", text):
        kind = re.search(r"\btype:\s*\"(\w+)\"", obj.group(0))
        found.append((obj.group(1), kind.group(1) if kind else ""))
    return found


# ---------- per-site lookups ----------

def youtube(link):
    data = get_json("https://www.youtube.com/oembed?format=json&url=" + urllib.parse.quote(link, safe=""))
    vid = re.search(r"(?:v=|youtu\.be/|shorts/|embed/)([\w-]{11})", link)
    image = f"https://i.ytimg.com/vi/{vid.group(1)}/hqdefault.jpg" if vid else data.get("thumbnail_url", "")
    return {"title": data.get("title", ""), "by": data.get("author_name", ""), "source": "YouTube", "image_url": image}


def spotify(link):
    data = get_json("https://open.spotify.com/oembed?url=" + urllib.parse.quote(link, safe=""))
    return {"title": data.get("title", ""), "source": "Spotify", "image_url": data.get("thumbnail_url", "")}


def wikidata_entity(qid):
    data = get_json(f"https://www.wikidata.org/wiki/Special:EntityData/{qid}.json")
    return data["entities"][qid]


def wikidata_labels(qids):
    if not qids:
        return []
    data = get_json(f"{WIKIDATA}?action=wbgetentities&format=json&props=labels&languages=en&ids=" + "|".join(qids[:4]))
    return [data["entities"][q]["labels"].get("en", {}).get("value", "") for q in qids[:4] if q in data.get("entities", {})]


def claims(entity, prop):
    out = []
    for c in entity.get("claims", {}).get(prop, []):
        value = c.get("mainsnak", {}).get("datavalue", {}).get("value")
        if value is not None:
            out.append(value)
    return out


def film_facts(qid):
    """Director, year and running time from Wikidata, plus the English Wikipedia title."""
    entity = wikidata_entity(qid)
    facts = {"title": entity.get("labels", {}).get("en", {}).get("value", "")}
    directors = [v["id"] for v in claims(entity, "P57") if isinstance(v, dict) and "id" in v]
    facts["by"] = ", ".join(wikidata_labels(directors))
    years = [v["time"][1:5] for v in claims(entity, "P577") if isinstance(v, dict) and "time" in v]
    facts["year"] = min(years) if years else ""
    runtime = [v for v in claims(entity, "P2047") if isinstance(v, dict) and "amount" in v]
    if runtime:
        facts["minutes"] = round(abs(float(runtime[0]["amount"])))
    facts["_wiki"] = entity.get("sitelinks", {}).get("enwiki", {}).get("title", "")
    return facts


def wikipedia_image(title, lang="en"):
    if not title:
        return ""
    data = get_json(f"https://{lang}.wikipedia.org/w/api.php?action=query&format=json&redirects=1"
                    f"&prop=pageimages&piprop=thumbnail&pithumbsize=500&pilicense=any&titles=" + urllib.parse.quote(title))
    for page in data.get("query", {}).get("pages", {}).values():
        return page.get("thumbnail", {}).get("source", "")
    return ""


def imdb(link):
    tt = re.search(r"(tt\d+)", link).group(1)
    hits = get_json(f"{WIKIDATA}?action=query&format=json&list=search&srsearch=haswbstatement:P345={tt}")
    results = hits.get("query", {}).get("search", [])
    if not results:
        raise LookupError(f"Wikidata doesn't know {tt}")
    facts = film_facts(results[0]["title"])
    facts["image_url"] = wikipedia_image(facts.pop("_wiki"))
    facts["source"] = "IMDb"
    return facts


def wikipedia(link):
    m = re.match(r"https?://(\w+)\.(?:m\.)?wikipedia\.org/wiki/([^#?]+)", link)
    lang, title = m.group(1), urllib.parse.unquote(m.group(2)).replace("_", " ")
    data = get_json(f"https://{lang}.wikipedia.org/w/api.php?action=query&format=json&redirects=1"
                    f"&prop=pageprops|pageimages&ppprop=wikibase_item&piprop=thumbnail&pithumbsize=500&pilicense=any&titles=" + urllib.parse.quote(title))
    page = next(iter(data.get("query", {}).get("pages", {}).values()), {})
    facts = {"title": page.get("title", title), "source": "Wikipedia", "image_url": page.get("thumbnail", {}).get("source", "")}
    qid = page.get("pageprops", {}).get("wikibase_item")
    if qid:
        extra = film_facts(qid)
        extra.pop("_wiki", None)
        facts.update({k: v for k, v in extra.items() if v})  # Wikidata's "Oppenheimer" beats "Oppenheimer (film)"
    facts["title"] = re.sub(r"\s+\((?:film|movie|documentary|TV series|podcast|\d{4} film)\)$", "", facts["title"])
    return facts


class MetaTags(HTMLParser):
    def __init__(self):
        super().__init__()
        self.meta, self.title, self._in_title = {}, "", False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "meta":
            key = (a.get("property") or a.get("name") or "").lower()
            if key and a.get("content") and key not in self.meta:
                self.meta[key] = a["content"]
        elif tag == "title":
            self._in_title = True

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False

    def handle_data(self, data):
        if self._in_title:
            self.title += data


def any_page(link):
    data, charset = get(link, "text/html,application/xhtml+xml")
    parser = MetaTags()
    parser.feed(data.decode(charset, "replace"))
    m = parser.meta
    host = urllib.parse.urlparse(link).netloc.replace("www.", "")
    published = m.get("article:published_time") or m.get("og:article:published_time") or m.get("date") or ""
    image = m.get("og:image") or m.get("twitter:image") or ""
    return {
        "title": squash(m.get("og:title") or m.get("twitter:title") or parser.title),
        "by": squash(m.get("author") or m.get("article:author") or ""),
        "source": squash(m.get("og:site_name") or host),
        "year": published[:4] if re.match(r"\d{4}", published) else "",
        "date": published[:10] if re.match(r"\d{4}-\d{2}-\d{2}", published) else "",
        "image_url": urllib.parse.urljoin(link, image) if image else "",
    }


def look_up(link):
    host = urllib.parse.urlparse(link).netloc.lower()
    if "youtube.com" in host or "youtu.be" in host:
        return youtube(link)
    if "open.spotify.com" in host:
        return spotify(link)
    if "imdb.com" in host and re.search(r"tt\d+", link):
        return imdb(link)
    if "wikipedia.org" in host and "/wiki/" in link:
        return wikipedia(link)
    return any_page(link)


# ---------- pictures ----------

def picture_type(data):
    if data[:3] == b"\xff\xd8\xff":
        return "jpg"
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return "png"
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "webp"
    if data[:6] in (b"GIF87a", b"GIF89a"):
        return "gif"
    return ""


def save_picture(link, url):
    if not url:
        return ""
    data, _ = get(url, "image/*", limit=4_000_000)
    kind = picture_type(data)
    if not kind or len(data) < 1500:
        return ""
    PICTURES.mkdir(parents=True, exist_ok=True)
    name = hashlib.sha1(link.encode()).hexdigest()[:12] + "." + kind
    (PICTURES / name).write_bytes(data)
    return f"assets/refs/{name}"


# ---------- the file ----------

def load_previous():
    if not OUT.exists():
        return {}
    m = re.search(r"NB\.media = (\{.*\});", OUT.read_text(encoding="utf-8"), re.S)
    return json.loads(m.group(1)) if m else {}


def render(media):
    body = ",\n".join(f"{json.dumps(k)}:{json.dumps(v, ensure_ascii=False, separators=(',', ':'))}" for k, v in sorted(media.items()))
    return HEADER + "NB.media = {\n" + body + ("\n" if body else "") + "};\n"


def main():
    links = log_links(REFERENCES.read_text(encoding="utf-8"))
    previous = load_previous()
    media, fresh, failed = {}, 0, []
    for link, kind in links:
        known = previous.get(link)
        if known and not known.get("error"):
            media[link] = known
            continue
        try:
            facts = look_up(link)
            facts["image"] = save_picture(link, facts.pop("image_url", ""))
            facts = {k: v for k, v in facts.items() if v not in ("", None)}
            facts["checked"] = date.today().isoformat()
            media[link] = facts
            fresh += 1
        except Exception as err:  # the next run tries again
            media[link] = {"error": str(err)[:160]}
            failed.append(f"{link}: {err}")
        time.sleep(0.5)

    used = {v.get("image", "").split("/")[-1] for v in media.values()}
    if PICTURES.exists():
        for pic in PICTURES.iterdir():
            if pic.is_file() and pic.name not in used:
                pic.unlink()

    text = render(media)
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{len(links)} links in the log: {fresh} looked up now, {len(failed)} to retry tomorrow.")
    for line in failed:
        print("  couldn't read", line)


if __name__ == "__main__":
    main()
